"""SBC for option A2n, and the liquidation-penalty misspecification check
(RESULTS 43.11).

**SBC set** (``scripts/run_optionA2n_sbc.sh``): 1,024 draws from the uniform
prior, generated by ``generate_dataset.py`` with every A2 training setting.
That means full grid, fixed solver, card type and R_gamma per block of 16
draws, PSID couples' seed pool (wealth and income), and 16 households each.
R_gamma is uniform on the A2w box [1.021, 1.075], the box the ensemble
estimates on; training covers it with two runs (main and strip). Seed
40,000,000: household streams (seed + draw + 1) overlap no training run (main
1-32,768, strip 100,001-103,072) and no earlier SBC set.

Every household's window carries the ensemble's observation noise
(``Spec.obs_noise``), seeded as training windows are. The SBC test is of the
whole generative process the network was trained on, noise included.

Scores are those of ``sbc_households.score``: coverage with a bootstrap over
blocks of 16 draws, KS on one household per draw (one per block for
R_gamma), and coverage by posterior-mean region, with regions on A2's box.

**Penalty check.** The illiquid liquidation penalty is fixed at Laibson et
al.'s schedule (RESULTS 41.3). The SBC set's first 512 draws are regenerated
at ``--liqpen_scale`` 0.5 and 1.5 with the same seed. That gives the same
theta, card, R_gamma, starting states, income and mortality shocks, windows
and noise; only the penalty differs. The network (trained at scale 1) scores
them against its posterior for the same households at scale 1: the paired
shift of posterior means, and coverage of the true theta. That is how far
the estimates move if the penalty is wrong by half.

Usage::

    PYTHONPATH=. .venv/bin/python scripts/sbc_optionA2.py --run_dirs outputs/optionA2n/s{0..4}
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import torch

from hh_npe.evaluation.weighted import sample_weighted
from hh_npe.npe.prior import PHASE3, sample_sobol
from scripts import optionA as oa
from scripts.sbc_households import score
from scripts.tail_diagnostic import BLOCK

SBC = Path("data/processed/optionA2_sbc16_shards")
PENALTY = {0.5: Path("data/processed/optionA2_sbc16_liqpen050_shards"),
           1.5: Path("data/processed/optionA2_sbc16_liqpen150_shards")}
TRAIN = Path("data/processed/couples_dataset_shards")
#: Settings an SBC set must share with the training generation (the rest:
#: seed, proposal, R_gamma range, notes).
SAME = ("simulator", "grid", "device", "gpu", "theta_batch", "chunk", "start_age",
        "n_waves", "wave_years", "store_panel", "n_households", "educ", "card_types",
        "crra_centred", "init_pool_sha256", "init_pool_n")
#: Posterior-mean regions on A2's box.
CUTS = {"beta": (0.30, 0.50, 0.80, 0.95, 1.00), "delta": (0.85, 0.95, 0.98, 1.00),
        "crra": (0.5, 1.0, 1.5, 2.5, 3.5, 5.0),
        "R_gamma": (1.021, 1.025, 1.04, 1.06, 1.075)}
LABEL = {"beta": r"$\beta$", "delta": r"$\delta$", "crra": r"$\rho$",
         "R_gamma": r"$R_\gamma$"}


def load_set(shards: Path, box, liqpen: float = 1.0):
    """theta per draw and the shard files, after checking the set was generated
    as training was, from the uniform prior on ``box``, at penalty ``liqpen``."""
    cfg = json.loads((shards / "solver_config.json").read_text())
    ref = json.loads((TRAIN / "solver_config.json").read_text())
    diff = {k: (cfg.get(k), ref.get(k)) for k in SAME if cfg.get(k) != ref.get(k)}
    if diff or cfg.get("proposal") != "uniform":
        raise SystemExit(f"{shards}: not generated as training was, from the uniform "
                         f"prior: {diff or cfg.get('proposal')}")
    if list(cfg["rgamma_range"]) != [box.rgamma_low, box.rgamma_high]:
        raise SystemExit(f"{shards}: R_gamma {cfg['rgamma_range']}, the ensemble's box "
                         f"{box.rgamma_low}-{box.rgamma_high}")
    if cfg.get("liqpen_scale", 1.0) != liqpen:
        raise SystemExit(f"{shards}: penalty scale {cfg.get('liqpen_scale', 1.0)}, "
                         f"expected {liqpen}")
    meta = []
    for f in sorted(shards.glob("shard_*.npz")):
        d = np.load(f)
        meta.append((int(d["lo"]), int(d["hi"]), d["theta"], f))
    meta.sort(key=lambda t: t[0])
    if not meta or [m[0] for m in meta] != [0] + [m[1] for m in meta[:-1]]:
        raise SystemExit(f"{shards}: shards do not tile a contiguous range from 0")
    theta = np.concatenate([m[2] for m in meta])
    if not np.allclose(theta[:, :3], sample_sobol(len(theta), PHASE3, seed=cfg["seed"]),
                       rtol=0, atol=1e-12):
        raise SystemExit(f"{shards}: theta is not the uniform Sobol sequence")
    blocks = theta[:, 3].reshape(-1, BLOCK) if len(theta) % BLOCK == 0 else None
    if blocks is None or not (blocks == blocks[:, :1]).all():
        raise SystemExit(f"{shards}: R_gamma is not constant within blocks of {BLOCK}")
    return theta, [m[3] for m in meta], cfg


def posterior(members, x, th, spec, n_draws):
    inv, lw = oa._weighting(members.proposal, spec)
    fb = spec.flow_box()
    torch.manual_seed(0)
    return sample_weighted(members.nets, x, n_draws, fb.low, fb.high, invert=inv,
                           log_weight=lw, truth=th)


class Members:
    def __init__(self, run_dirs, device):
        self.nets, self.proposal, self.cfg = oa.load_members(run_dirs, device)


def show(s: dict, title: str) -> None:
    f = lambda d: f"{d['rate']:.3f} ({d['ci90'][0]:.3f}-{d['ci90'][1]:.3f})"
    print(f"\n=== {title}: {s['n_households']} households from {s['n_draws']} draws ===")
    print(f"{'':10s}{'coverage (90% CI)':>26s}{'KS p, 1 per draw':>18s}")
    for n in oa.BOX.names:
        print(f"{n:10s}{f(s['coverage_90'][n]):>26s}{s['ks_p_one_per_draw'][n]:18.3f}")
    print("by posterior-mean region: coverage / above 95th / below 5th")
    for n in oa.BOX.names:
        for r in s["by_posterior_mean"][n]:
            if "coverage_90" not in r:
                print(f"  {n:8s}[{r['lo']:g}, {r['hi']:g})  n={r['n']}")
                continue
            print(f"  {n:8s}[{r['lo']:g}, {r['hi']:g})  n={r['n']:5d} ({r['n_draws']:4d} draws)"
                  f"  {f(r['coverage_90'])}  {f(r['above_95'])}  {f(r['below_5'])}")


def figure(u: np.ndarray, one: np.ndarray, path: Path, title: str) -> None:
    """ECDF of the ranks minus the uniform, per parameter, one household per
    draw; the band is the KS 95% band for its n."""
    import matplotlib.pyplot as plt

    grid = np.linspace(0, 1, 201)
    fig, axs = plt.subplots(1, 4, figsize=(15, 3.6), sharey=True)
    for j, (ax, n) in enumerate(zip(axs, oa.BOX.names)):
        uu = u[one, j]
        uu = uu[np.isfinite(uu)]
        ax.plot(grid, (uu[:, None] <= grid).mean(0) - grid, color="#1f77b4",
                label="1 household per draw")
        uall = u[np.isfinite(u[:, j]), j]
        ax.plot(grid, (uall[:, None] <= grid).mean(0) - grid, color="#ff7f0e", lw=1,
                label="all households")
        band = 1.358 / np.sqrt(len(uu))
        ax.fill_between(grid, -band, band, color="0.85", label="KS 95% band (1 per draw)")
        ax.axhline(0, color="0.4", lw=0.8)
        ax.set_title(LABEL[n])
        ax.set_xlabel("rank u")
    axs[0].set_ylabel("ECDF(u) - u")
    axs[0].legend(fontsize=8, loc="lower left")
    fig.suptitle(title)
    fig.tight_layout()
    fig.savefig(path, dpi=130)
    plt.close(fig)


def penalty_check(members, spec, theta_base, files_base, n_draws, sets=PENALTY) -> dict:
    """Posterior shifts and coverage at penalty 0.5 and 1.5 against 1, paired
    by household (same first shard, seed, windows and noise)."""
    n = len(np.load(files_base[0])["theta"])
    th0, x0, pid0, _ = oa.windows(files_base[:1], theta_base, seed=oa.SBC_SEED,
                                  noise=spec.obs_noise)
    th0 = th0.numpy().astype(float)
    r0 = posterior(members, x0, th0, spec, n_draws)
    out = {"n_draws": n, "n_households": int(len(th0)), "by_scale": {}}
    names = list(oa.BOX.names)
    print(f"\npenalty check: {len(th0)} households from the first {n} SBC draws")
    print(f"{'':16s}" + "".join(f"{k:>34s}" for k in names))
    print(f"{'':16s}" + "".join(f"{'shift med (p10, p90) / cov90':>34s}" for _ in names))
    cov0 = (r0["lo"] <= th0) & (th0 <= r0["hi"])
    print(f"{'scale 1':16s}" + "".join(f"{'':>26s}{cov0[:, j].mean():8.3f}"
                                     for j in range(len(names))))
    for s, shards in sets.items():
        if not shards.exists():
            print(f"scale {s}: {shards} missing; skipped")
            continue
        theta_s, files_s, _cfg = load_set(shards, spec.box, liqpen=s)
        if not np.array_equal(theta_s[:n], theta_base[:n]):
            raise SystemExit(f"{shards}: draws differ from the SBC set's")
        th1, x1, pid1, _ = oa.windows(files_s[:1], theta_s, seed=oa.SBC_SEED,
                                      noise=spec.obs_noise)
        th1 = th1.numpy().astype(float)
        if not (np.array_equal(pid1.numpy(), pid0.numpy()) and np.array_equal(th1, th0)):
            raise SystemExit(f"{shards}: households are not paired with the SBC set's")
        r1 = posterior(members, x1, th1, spec, n_draws)
        ok = np.isfinite(r0["mean"][:, 0]) & np.isfinite(r1["mean"][:, 0])
        d = (r1["mean"] - r0["mean"])[ok] / spec.prior_sd
        cov = ((r1["lo"] <= th1) & (th1 <= r1["hi"]))[ok]
        row = {}
        for j, k in enumerate(names):
            row[k] = {"shift_over_prior_sd_median": float(np.median(d[:, j])),
                      "shift_over_prior_sd_p10": float(np.percentile(d[:, j], 10)),
                      "shift_over_prior_sd_p90": float(np.percentile(d[:, j], 90)),
                      "shift_median": float(np.median(d[:, j]) * spec.prior_sd[j]),
                      "cov90": float(cov[:, j].mean()),
                      "cov90_scale1": float(cov0[ok, j].mean())}
        out["by_scale"][str(s)] = row
        print(f"{'scale ' + str(s):16s}" + "".join(
            f"{row[k]['shift_over_prior_sd_median']:+9.3f} ({row[k]['shift_over_prior_sd_p10']:+.2f}, "
            f"{row[k]['shift_over_prior_sd_p90']:+.2f}){row[k]['cov90']:8.3f}" for k in names))
    print("(shifts in prior sds of each parameter: posterior mean at the scale minus at 1)")
    return out


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--run_dirs", type=Path, nargs="+", required=True)
    ap.add_argument("--shards", type=Path, default=SBC)
    ap.add_argument("--penalty", nargs="*", default=[f"{k}={v}" for k, v in PENALTY.items()],
                    metavar="SCALE=SHARDS", help="The penalty sets (smoke tests: others).")
    ap.add_argument("--n_draws", type=int, default=2000)
    ap.add_argument("--device", default="cuda" if torch.cuda.is_available() else None)
    ap.add_argument("--out", type=Path, default=Path("outputs/optionA2n/sbc"))
    ap.add_argument("--figure", type=Path, default=Path("figures/45_sbc_optionA2n.png"))
    args = ap.parse_args()

    members = Members(args.run_dirs, args.device)
    spec = oa.spec_of(members.cfg)
    theta_all, files, cfg = load_set(args.shards, spec.box)
    th, x, pid, _f = oa.windows(files, theta_all, seed=oa.SBC_SEED, noise=spec.obs_noise)
    th, pid = th.numpy().astype(float), pid.numpy()
    one = np.zeros(len(pid), bool)
    one[oa.one_per_draw(torch.from_numpy(pid), seed=0)] = True
    print(f"{len(members.nets)} members; {spec.describe()}\n{len(th)} households from "
          f"{len(np.unique(pid))} draws (seed {cfg['seed']}, {len(files)} shards)", flush=True)

    r = posterior(members, x, th, spec, args.n_draws)
    s = score(r, th, pid, one, cuts=CUTS)
    args.out.mkdir(parents=True, exist_ok=True)
    np.savez(args.out / "sbc16.npz", truth=th, pid=pid, one_per_draw=one,
             **{k: r[k] for k in ("mean", "sd", "lo", "hi", "u", "ess")})
    show(s, "SBC, " + ", ".join(map(str, args.run_dirs)))
    res = {"shards": str(args.shards), "seed": cfg["seed"], "run_dirs": list(map(str, args.run_dirs)),
           "spec": spec.describe(), "sbc": s}
    sets = {float(k): Path(v) for k, v in (a.split("=", 1) for a in args.penalty)}
    res["penalty"] = penalty_check(members, spec, theta_all, files, args.n_draws, sets)
    (args.out / "sbc16.json").write_text(json.dumps(res, indent=2))
    figure(r["u"], one & np.isfinite(r["u"]).all(1), args.figure,
           "Option A2n: SBC rank calibration on 1,024 uniform-prior draws, 16 households "
           "each, with the training observation noise; R_gamma ranks are shared within "
           "blocks of 16 draws")
    print(f"\nwrote {args.out}/ and {args.figure}")


if __name__ == "__main__":
    main()
